function compactQuestions(qs, maxChars){
  // Preserve every question. Only whitespace/punctuation is compacted.
  let lines=qs.map((q,i)=>`Q${i+1}. ${String(q).replace(/\s+/g," ").trim()}\nA${i+1}.`);
  let block=lines.join("\n");
  if(block.length<=maxChars) return block;
  // We never delete a question. Remove optional spacing and shorten labels only as last resort.
  lines=qs.map((q,i)=>`${i+1})${String(q).replace(/\s+/g," ").trim()}\nA${i+1}:`);
  return lines.join("\n");
}

