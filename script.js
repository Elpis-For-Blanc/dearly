let cropTarget=null,cropSource=null,cropData={x:0,y:0,scale:1,baseScale:1,w:0,h:0},drag=null;

function drawCropPreview(){
  if(!cropSource)return;
  const stage=$("cropStage"), canvas=$("cropCanvas");
  const cssW=stage.clientWidth, cssH=stage.clientHeight;
  if(!cssW||!cssH)return;

  const dpr=Math.max(1,window.devicePixelRatio||1);
  const pxW=Math.round(cssW*dpr), pxH=Math.round(cssH*dpr);
  if(canvas.width!==pxW||canvas.height!==pxH){canvas.width=pxW;canvas.height=pxH}
  const ctx=canvas.getContext("2d");
  ctx.setTransform(dpr,0,0,dpr,0,0);
  ctx.clearRect(0,0,cssW,cssH);
  ctx.fillStyle="#f8eef2";ctx.fillRect(0,0,cssW,cssH);

  const s=cropData.baseScale*cropData.scale;
  const w=cropData.w*s,h=cropData.h*s;
  const maxX=Math.max(0,(w-cssW)/2),maxY=Math.max(0,(h-cssH)/2);
  cropData.x=Math.max(-maxX,Math.min(maxX,cropData.x));
  cropData.y=Math.max(-maxY,Math.min(maxY,cropData.y));
  const left=(cssW-w)/2+cropData.x, top=(cssH-h)/2+cropData.y;
  const fallback=$("cropFallback");
  if(fallback){
    fallback.style.objectFit="cover";
    fallback.style.transform=`translate(${cropData.x}px,${cropData.y}px) scale(${cropData.scale})`;
  }
  try{
    ctx.drawImage(cropSource,left,top,w,h);
    $("cropStatus").textContent=$("cropStatus").textContent.replace(/ · Canvas:.*/,"")+" · Canvas: 정상";
  }catch(err){
    $("cropStatus").textContent=$("cropStatus").textContent.replace(/ · Canvas:.*/,"")+` · Canvas 오류: ${err.message}`;
  }
}

function openCrop(file,target){
  if(!file)return;
  const reader=new FileReader();
  reader.onerror=()=>alert("이미지를 불러오지 못했어요.");
  reader.onload=()=>{
    const source=new Image();
    source.onload=()=>{
      cropTarget=target;cropSource=source;
      cropData.w=source.naturalWidth;cropData.h=source.naturalHeight;
      cropData.scale=1;cropData.x=0;cropData.y=0;
      const modal=$("cropModal");
      const fallback=$("cropFallback");
      fallback.src=reader.result;
      fallback.style.display="block";
      $("cropStatus").textContent=`이미지 로드 성공 · ${cropData.w}×${cropData.h}`;
      modal.classList.add("open");modal.setAttribute("aria-hidden","false");
      $("cropZoom").value=1;
      requestAnimationFrame(()=>{
        const stage=$("cropStage");
        cropData.baseScale=Math.max(stage.clientWidth/cropData.w,stage.clientHeight/cropData.h);
        $("cropStatus").textContent+=` · 크롭창 ${stage.clientWidth}×${stage.clientHeight}`;
        drawCropPreview();
        // Canvas가 브라우저에서 늦게 갱신되는 경우에도 재시도.
        setTimeout(drawCropPreview,80);
        setTimeout(drawCropPreview,300);
      });
    };
    source.onerror=()=>alert("이미지를 읽을 수 없어요. JPG, PNG 또는 WebP 파일을 사용해주세요.");
    source.src=reader.result;
  };
  reader.readAsDataURL(file);
}
