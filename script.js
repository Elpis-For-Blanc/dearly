let cropTarget=null,cropData={x:0,y:0,scale:1,baseScale:1,w:0,h:0},drag=null;
function openCrop(file,target){
  const r=new FileReader();
  r.onload=e=>{
    cropTarget=target;
    const ci=$("cropImage");
    ci.onload=()=>{
      const stage=$("cropStage"), sw=stage.clientWidth, sh=stage.clientHeight;
      cropData.w=ci.naturalWidth; cropData.h=ci.naturalHeight;
      cropData.baseScale=Math.max(sw/cropData.w,sh/cropData.h);
      cropData.scale=1; cropData.x=0; cropData.y=0; $("cropZoom").value=1;
      positionCrop(); $("cropModal").classList.add("open"); $("cropModal").setAttribute("aria-hidden","false");
    };
    ci.src=e.target.result;
  }; r.readAsDataURL(file);
}
function positionCrop(){
  const ci=$("cropImage"), stage=$("cropStage"), s=cropData.baseScale*cropData.scale;
  const w=cropData.w*s,h=cropData.h*s;
  const maxX=Math.max(0,(w-stage.clientWidth)/2),maxY=Math.max(0,(h-stage.clientHeight)/2);
  cropData.x=Math.max(-maxX,Math.min(maxX,cropData.x));cropData.y=Math.max(-maxY,Math.min(maxY,cropData.y));
  ci.style.width=w+"px";ci.style.height=h+"px";ci.style.left=(stage.clientWidth-w)/2+cropData.x+"px";ci.style.top=(stage.clientHeight-h)/2+cropData.y+"px";
}
