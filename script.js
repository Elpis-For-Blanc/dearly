function ensureQuestionState(){
  current.forEach(x=>{
    if(typeof x.locked!=="boolean") x.locked=false;
    if(!x.uid) x.uid="q_"+Date.now().toString(36)+"_"+Math.random().toString(36).slice(2,8);
  });
}
function poolForCurrentCategory(){
  const cat=$("category").value;
  return cat==="random" ? Object.values(banks).flat() : (banks[cat]||[]);
}
function freshQuestion(exclude=[]){
  const pool=poolForCurrentCategory().filter(q=>!exclude.includes(q));
  const source=pool.length ? pool : poolForCurrentCategory();
  if(!source.length) return null;
  return source[Math.floor(Math.random()*source.length)];
}
function rerollOne(i){
  ensureQuestionState();
  const used=current.map(x=>x.q);
  const next=freshQuestion(used);
  if(!next){ alert("바꿀 수 있는 다른 질문이 없어요."); return; }
  current[i]={q:next,a:"",locked:false,uid:current[i].uid};
  renderEditor(); renderCard();
  if($("oocOutput")?.value) buildOoc();
}
function toggleKeep(i){
  ensureQuestionState();
  current[i].locked=!current[i].locked;
  renderEditor();
}
function moveQuestion(from,to){
  if(from===to || from<0 || to<0 || from>=current.length || to>=current.length) return;
  const [item]=current.splice(from,1);
  current.splice(to,0,item);
  renderEditor(); renderCard();
  if($("oocOutput")?.value) buildOoc();
}
function moveQuestionStep(i,delta){
  const to=i+delta;
  if(to<0 || to>=current.length) return;
  moveQuestion(i,to);
}

