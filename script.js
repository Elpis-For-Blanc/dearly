function renderBalanceEditor(){
  const editor=document.getElementById("editor");
  if(!editor)return;
  editor.innerHTML="";
  balancePairs.forEach((p,i)=>{
    const wrap=document.createElement("div");
    wrap.className="qitem balance-card";
    wrap.innerHTML=`
      <div class="qnum">Q${i+1}. 둘 중 하나만 고른다면?</div>
      <div class="balance-choice">
        <button type="button" data-side="A">${p[0]}</button>
        <span class="balance-vs">OR</span>
        <button type="button" data-side="B">${p[1]}</button>
      </div>
      <div class="balance-result">${balanceAnswers[i] ? "선택: "+balanceAnswers[i] : "아직 선택하지 않았어요"}</div>`;
    wrap.querySelectorAll("button[data-side]").forEach(btn=>{
      if(balanceAnswers[i]===btn.textContent)btn.classList.add("selected");
      btn.onclick=()=>{
        balanceAnswers[i]=btn.textContent;
        renderBalanceEditor();
        syncBalancePreview();
      };
    });
    editor.appendChild(wrap);
  });
  syncBalancePreview();
}

function syncBalancePreview(){
  // Feed selections into existing answer fields/preview when those elements exist.
  balancePairs.forEach((p,i)=>{
    const ans=balanceAnswers[i]||"";
    const el=document.querySelector(`[data-answer-index="${i}"]`);
    if(el)el.value=ans;
  });
  try{ renderPreview?.(); }catch(e){}
}

